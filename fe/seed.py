def build_rows() -> list[dict]:
    rows = []
    for i, (slug, title, subtitle, kind, orient, theme, pal, verse, ref, scene, extra, best) in enumerate(P):
        cols = {"todos", "regalos", "minimalistas"}
        cols.update(THEME_TO_COLLECTIONS.get(theme, []))
        cols.update(extra)
        if "mujer" in cols:
            cols.discard("mujer"); cols.add("cuadros-mujer")
        if "hombre" in cols:
            cols.discard("hombre"); cols.add("cuadros-hombre")
        if pal in ("beige", "blanco", "dorado"):
            cols.add("cuadros-beige")
        if orient == "h":
            cols.update(["salon", "comedor", "recibidor", "despacho"])
            if kind == "lienzo":
                cols.add("grandes")
        else:
            cols.update(["verticales", "dormitorio", "recibidor", "rincon-oracion"])
        if kind == "lamina":
            cols.add("pequenos")
        if verse:
            cols.add("versiculos") if kind == "lamina" and "versiculo" in subtitle.lower() else None
        rows.append({
            "slug": slug, "title": title, "subtitle": subtitle, "kind": kind, "orient": orient, "theme": theme,
            "palette": pal, "verse": verse, "verse_ref": ref, "art_prompt": scene,
            "collections": sorted(c for c in cols if c in {x[0] for x in COLLECTIONS}),
            "bestseller": best, "sort": i,
        })
    return rows
